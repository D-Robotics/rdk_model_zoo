export function taskTranslationKey(task: string): TranslationKey {
  if (Object.prototype.hasOwnProperty.call(manifestTaskTranslationKeys, task)) {
    return manifestTaskTranslationKeys[task as ManifestTaskId];
  }

  return "task.unknown";
}

const placeholderPattern = /\{([a-zA-Z0-9_.-]+)\}/g;

export function t(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const dictionary = translations[locale];
  const value = dictionary?.[key];
  if (typeof value !== "string") {
    throw new Error(`Missing translation for key "${String(key)}" in locale "${String(locale)}"`);
  }

  return value.replace(placeholderPattern, (placeholder, name: string) => {
    if (!params || !Object.prototype.hasOwnProperty.call(params, name)) {
      return placeholder;
    }
    return String(params[name]);
  });
}
